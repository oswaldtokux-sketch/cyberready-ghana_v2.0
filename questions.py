def get_assessment_questions():
    """
    Randomly select 20 questions evenly from each category (4 questions per category).
    This ensures users get different questions each time they attempt the assessment.
    """
    import random
    
    # Group questions by category
    categories = {}
    for question in QUESTIONS:
        category = question["category"]
        if category not in categories:
            categories[category] = []
        categories[category].append(question)
    
    # Select 4 random questions from each category
    selected_questions = []
    for category in sorted(categories.keys()):
        selected_questions.extend(random.sample(categories[category], 4))
    
    # Shuffle to randomize order
    random.shuffle(selected_questions)
    
    return selected_questions